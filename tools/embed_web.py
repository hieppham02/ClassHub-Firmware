"""Generate the C page asset without relying on PlatformIO/IDF embed-file paths."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = (root / 'src/web_console.html').read_text(encoding='utf-8')
result = '// Generated by tools/embed_web.py from web_console.html.\n#pragma once\nstatic const char CAMERA_WEB_PAGE[] =\n'
result += '\n'.join('    '+json.dumps(line, ensure_ascii=False) for line in source.splitlines(keepends=True))+';\n'
target = root / 'src/web_console.h'
if '--check' in sys.argv:
    if not target.exists() or target.read_text(encoding='utf-8') != result:
        sys.exit('Web asset is stale; run py tools/embed_web.py')
else:
    target.write_text(result, encoding='utf-8')
